/** Capacités.xlsx -> Pokémon move catalogue (including worksheet subcategories).
 * Usage: node tools/xlsx/extract-capacites.mjs [input.xlsx] [output.mjs]
 * Reads the original XLSX XML; never modifies the workbook.
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { pathToFileURL } from "node:url";

const input = path.resolve(process.argv[2] ?? path.join(os.homedir(), "Downloads", "Capacités.xlsx"));
const output = path.resolve(process.argv[3] ?? "module/data/pokemon-moves-data.mjs");
const typeNames = ["Acier", "Combat", "Dragon", "Electrique", "Eau", "Fée", "Feu", "Glace",
  "Insecte", "Normal", "Plante", "Poison", "Psy", "Roche", "Sol", "Spectre", "Ténèbres", "Vol"];
const slug = text => String(text).toLocaleLowerCase("fr").normalize("NFD")
  .replace(/[\u0300-\u036f]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const typeKey = name => ({ Electrique: "electrik" })[name] ?? slug(name);
if (!fs.existsSync(input)) throw new Error(`Workbook not found: ${input}`);
const temp = fs.mkdtempSync(path.join(os.tmpdir(), "lobia-capacites-"));
try {
  execFileSync("jar", ["xf", input], { cwd: temp });
  process.env.XLSX_DIR = temp;
  const { sharedStrings, sheetCells, refToXY, decode } = await import("./parse.mjs");
  const strings = sharedStrings();
  const workbook = fs.readFileSync(path.join(temp, "xl/workbook.xml"), "utf8");
  const rels = fs.readFileSync(path.join(temp, "xl/_rels/workbook.xml.rels"), "utf8");
  const targets = new Map([...rels.matchAll(/<Relationship\b([^>]*?)\/>/g)]
    .map(([, attrs]) => [/\bId="([^"]+)"/.exec(attrs)?.[1], /\bTarget="([^"]+)"/.exec(attrs)?.[1]]));
  const sheets = [...workbook.matchAll(/<sheet\b([^>]*?)\/>/g)].map(([, attrs]) => {
    const name = decode(/\bname="([^"]+)"/.exec(attrs)?.[1] ?? "");
    const target = targets.get(/\br:id="([^"]+)"/.exec(attrs)?.[1]);
    if (!target?.match(/(?:^|\/)sheet\d+\.xml$/)) throw new Error(`Unknown worksheet for ${name}`);
    return { name, file: path.basename(target) };
  });
  if (sheets.length !== typeNames.length || sheets.some((sheet, i) => sheet.name !== typeNames[i])) {
    throw new Error(`Unexpected type sheets: ${sheets.map(sheet => sheet.name).join(", ")}`);
  }

  const categories = [];
  const moves = [];
  const keys = new Set();
  const categoryKeys = new Set();
  for (const sheet of sheets) {
    const rows = new Map();
    // G/H hold unrelated workbook calculations; only A–F are part of the move table.
    for (const [ref, value] of sheetCells(sheet.file, strings)) {
      const { col, row } = refToXY(ref);
      if (col > 6) continue;
      (rows.get(row) ?? rows.set(row, {}).get(row))[col] = String(value).trim();
    }
    const header = rows.get(1) ?? {};
    if (["Nom", "Classe", "Dégât", "Difficulté", "Contact", "Description"]
      .some((value, i) => header[i + 1] !== value)) throw new Error(`${sheet.name}: unexpected headers`);
    let category = null;
    for (const [row, cells] of [...rows].sort(([a], [b]) => a - b)) {
      if (row === 1 || !Object.keys(cells).length) continue;
      if (!cells[1]) throw new Error(`${sheet.name} row ${row}: values without a name`);
      if (Object.keys(cells).length === 1) {
        category = slug(cells[1]);
        if (!category) throw new Error(`${sheet.name} row ${row}: empty subcategory key`);
        if (!categoryKeys.has(category)) {
          categoryKeys.add(category);
          categories.push({ key: category, name: cells[1] });
        } else if (categories.find(entry => entry.key === category).name !== cells[1]) {
          throw new Error(`${sheet.name} row ${row}: conflicting subcategory ${cells[1]}`);
        }
        continue;
      }
      if (!category || [2, 3, 4, 5, 6].some(col => cells[col] === undefined)) {
        throw new Error(`${sheet.name} row ${row}: incomplete move ${JSON.stringify(cells)}`);
      }
      const key = `${typeKey(sheet.name)}-${slug(cells[1])}`;
      if (keys.has(key)) throw new Error(`Duplicate move ${key} (${sheet.name} row ${row})`);
      keys.add(key);
      moves.push({ key, type: typeKey(sheet.name), category, name: cells[1],
        class: cells[2], damage: cells[3], difficulty: cells[4],
        contact: cells[5], description: cells[6] });
    }
  }
  if (categories.length !== 25 || moves.length !== 1093) {
    throw new Error(`Unexpected subcategory/move count: ${categories.length}/25, ${moves.length}/1093`);
  }
  const text = `/** Generated by tools/xlsx/extract-capacites.mjs from ${path.basename(input)}. Do not edit by hand. */\n`
    + `export const POKEMON_MOVE_CATEGORIES = ${JSON.stringify(categories, null, 2)};\n`
    + `export const POKEMON_MOVES = ${JSON.stringify(moves, null, 2)};\n`;
  fs.writeFileSync(output, text);
  const written = await import(`${pathToFileURL(output).href}?check=${Date.now()}`);
  if (written.POKEMON_MOVES.length !== moves.length || written.POKEMON_MOVE_CATEGORIES.length !== categories.length) {
    throw new Error("Generated move module verification failed");
  }
  console.log(`Pokémon moves: ${moves.length} across ${sheets.length} types and ${categories.length} subcategories (verified on disk)`);
} finally {
  fs.rmSync(temp, { recursive: true, force: true });
}
